// Real national exams with original methodological corrections written for modarisi.ma.
// Exam prompts are the ministry's short instruction lines; long excerpts from authors are
// summarized (not reproduced) because they are copyrighted.

export type ExamSubjectKind = "question" | "quote" | "text" | "documents" | "essay";

export type CorrectionSection = { heading: string; points: string[] };

export type ExamPart = {
  kind: ExamSubjectKind;
  label: string; // "الموضوع الأول"
  /** Short ministry instruction / question, quoted as written. */
  prompt: string;
  /** Short quote given in the exam (only when short). */
  quote?: string;
  /** Our own one-sentence summary of a long excerpt. */
  summary?: string;
  author?: string;
  module: string; // المجزوءة / المحور
  concept: string; // المفهوم والمحور / الدرس
  /** Points for this part, e.g. "10 نقط". */
  points?: string;
  /** Sub-questions or essay items, as written (points in parentheses). */
  items?: string[];
  /** Documents: title/source and our one-line description (never the full text). */
  documents?: { ref: string; source: string; about: string }[];
  /** True when the candidate picks one of several parts (e.g. essay topic 1 or 2). */
  optional?: boolean;
  correction: CorrectionSection[];
};

export type NationalExam = {
  slug: string;
  subject: string;
  trackId: "sciences-humaines" | "lettres";
  trackAr: string;
  year: number;
  session: "العادية" | "الاستدراكية";
  duration: string;
  coef: number;
  parts: ExamPart[];
  /** Where the full official paper can be downloaded (third-party archives). */
  paperSources: { label: string; url: string }[];
  /** Anything we could not confirm from two sources. */
  caveat?: string;
  /** Short explanation of how the paper is organised (shown under the title). */
  structure?: string;
  /** Prefix for the "ask the tutor" link. */
  tutorPrefix?: string;
};

