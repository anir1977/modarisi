export const conceptBySlug = (slug: string) => CONCEPTS.find((c) => c.slug === slug);

/** Find the lesson matching an exam part's concept text, e.g. "مفهوم الغير · محور وجود الغير". */
export function lessonForConcept(text: string): Concept | undefined {
  const head = text.split("·")[0];
  return CONCEPTS.find((c) => [c.name, ...(c.aliases ?? [])].some((n) => head.includes(`مفهوم ${n}`)));
}
